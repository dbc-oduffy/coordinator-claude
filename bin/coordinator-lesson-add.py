def _machine_local_get(key: str):
    """Call machine-local get <key> and return the value, or None on failure.

    Mirrors coordinator-queue-append._machine_local_get(). Settings-home
    first (DR-210 Amendment 2026-07-24: "resolves nothing through
    ~/.claude/bin"), falling back to the retired compat mirror only when the
    settings-home candidate is absent on disk. Delegates to
    machine_local_impl_resolve.machine_local_impl_path() (shared resolver —
    review: code-reviewer F3, was a hand-rolled duplicate of that ladder).
    """
    impl = _mlir_machine_local_impl_path(_MACHINE_LOCAL_IMPL_ENV)
    try:
        from coordinator_core.win_portability import no_console_creationflags, no_console_passthrough_kwargs

        result = subprocess.run(
            [sys.executable, impl, "get", key],
            capture_output=True,
            text=True,
            **no_console_creationflags(),
        )
    except OSError:
        return None
    if result.returncode != 0 or not result.stdout.strip():
        return None
    return result.stdout.strip()



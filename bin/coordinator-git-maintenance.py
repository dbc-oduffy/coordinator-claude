"""
coordinator-git-maintenance — CLI trampoline over claude-klabauter
coordinator_core.ops.git_maintenance.

Purpose: give the six ceremony call sites in doe-claude-em's tree something to
invoke. They call a BIN, not an op; `coordinator_core.ops.git_maintenance`
registers `git.maintenance` and is reachable over IPC, but an op alone is not
reachable from a ceremony command file. This file is that missing door.

    coordinator-git-maintenance <hourly|daily|weekly>

No argv parsing beyond the TIER. An option surface here would be a second way to
say what the tier already says, and every flag added at this layer is one the op
must then also honour over IPC.

WHY A `.py` AND NOT A HAND-WRITTEN `.exe`. The memo's part-4 CLI contract asks
for a native `.exe` door, and it gets one — but nothing hand-writes a native
image. The mechanism, in three steps, is:

  1. this thin trampoline lands at `coordinator/bin/` (the same shape as
     `coordinator/bin/coordinator-reap-stale-locks.py` over
     `coordinator_core.ops.reap_stale_locks`);
  2. `coordinator_core/install/substrate.py :: _derive_agent_helper_target_map`
     discovers it on the next install and writes the ordinary `.py`/`.cmd`
     forwarder pair;
  3. IF the name is present in the door-eligible bucket of
     `coordinator_core/ops/warm_entrypoint_allowlist.json`,
     `substrate.py :: _cut_over_to_native_door` promotes it to a native `.exe`
     and REMOVES the `.py`/`.cmd` pair on that same install. That removal is the
     "kill", not an additive step.

This file creates the trampoline and lets the next allowlist regeneration pick it
up. It does NOT hand-edit that allowlist: the file is machine-generated by
`forwarder_door_census.py --write-allowlist` from the full generator-known
`coordinator/bin/` population, and a union-with-prior-content hand edit already
caused one drift incident (see the allowlist's own header comment).

A door fix is inert until the installed images are rewritten — landing this file
does not make `coordinator-git-maintenance` callable from a session that has not
re-run the installer.

Exit codes (matching `coordinator_core.ops.git_maintenance.main`):
  0 — the tier ran, or deferred, or lost the maintenance.lock race. All three
      are no-harm outcomes and all three print what happened; a caller reading
      only the exit code cannot tell them apart, which is why they are
      reported rather than merely returned.
  1 — a leg failed (the maintenance run, the prune, or an orphan-pack unlink).
  2 — usage error (missing or unknown TIER), or the transport failed:
      engine-root resolution or the op module was not importable. The two
      share the numeral but are printed with distinct, greppable stderr lines
      so they are never confused in practice.

Spec backlink: docs/plans/2026-08-30-ceremony-driven-git-maintenance.md § C9.
"""

import sys


def _import_runner():
    """Resolve the engine root, put it on sys.path, and import the shared
    in-process runner.

    Reuses cc_invoke's engine-root resolution ladder (env var -> settings-home
    pointer file -> coordinator-claude-klabauter-root.sh) rather than re-deriving it.
    This is a plain in-process import, not an RPC invoke, so cc_invoke's
    subprocess-spawn transport is deliberately NOT used — same variant-#1
    direct-import shape as coordinator-reap-stale-locks.

    DR-276: the op runs through `coordinator_core.cli_entry.run_op_main`
    rather than by importing and calling its `main` directly, so anything it
    declares becomes a session scope-touch claim.
    """
    import lib  # noqa: F401 — bootstraps coordinator/bin/lib onto sys.path
    from cc_invoke import require_dispatch_engine_on_path

    require_dispatch_engine_on_path()
    from coordinator_core.cli_entry import run_op_main

    return run_op_main


def main(argv: "list[str] | None" = None) -> int:
    args = sys.argv[1:] if argv is None else list(argv)

    try:
        run_op_main = _import_runner()
    except RuntimeError as exc:
        print(
            f"coordinator-git-maintenance: engine-root resolution failed: {exc}",
            file=sys.stderr,
        )
        return 2
    except ImportError as exc:
        print(
            f"coordinator-git-maintenance: coordinator_core.cli_entry not importable: {exc}",
            file=sys.stderr,
        )
        return 2

    try:
        code = run_op_main("coordinator_core.ops.git_maintenance", args)
    except ImportError as exc:
        print(
            f"coordinator-git-maintenance: coordinator_core.ops.git_maintenance not importable: {exc}",
            file=sys.stderr,
        )
        return 2

    return code


if __name__ == "__main__":
    sys.exit(main())

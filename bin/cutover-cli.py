"""cutover-cli — operator forwarder for the cutover state machine primitive
(coordinator_core.ops.cutover_gate / cutover_advance).

Purpose: the ONLY sanctioned route to (a) inspect a cutover record's current
coverage verdict and (b) advance its phase. `advance` is the route named by
the F4 hard-deny write guard (`write_guards/block_cutover_phase_hand_edit.py`)
when it refuses a hand-edit of a cutover record's `phase` field — this
forwarder is what that refusal message points operators at.

Spec backlink: docs/plans/2026-07-25-cutover-state-machine.md § C7, § D1, § D4,
§ AC6. Modeled on `coordinator/bin/review-coverage-gate.py`'s per-op
`cc_invoke.route()` trampoline shape (the sanctioned-advance precedent D1
cites) and `coordinator/bin/archive-stamp-cli.py`'s direct-import subcommand
dispatch shape (help-flag handling, CLAUDE_KLABAUTER_ROOT transport-failure exit code).

Subcommands
    show <record_path>
        Read-only(*) coverage check: invokes `cutover.gate` and prints the
        verdict without touching `phase`. (*) `cutover.gate` itself appends
        one `derivation_history` entry per call per its own contract (plan
        § C4b) — this forwarder does not add or suppress that side effect.

    confirm-consumer <record_path> --id <id> --verified-by-kind
                      <test-node-id|probe-op-key|commit-sha> --verified-by-ref <ref>
                      [--verified-at <ISO-8601>]
        Appends one entry to the record's `confirmed_consumers` list. NOT
        routed through an op: per plan § D4/D3, only the `phase` field is
        write-guarded and gate-mediated — populating the claim being tested
        (§ "The load-bearing design decision": "`confirmed_consumers` is the
        claim being tested, never the source of truth") is ordinary record
        authoring, the same act C11-C17 perform by hand on other records.
        Mutates frontmatter via `coordinator_core.frontmatter.primitives`
        (`split_frontmatter`/`rebuild`) rather than a hand-rolled regex
        fence-scan, per the raw-frontmatter-reads-break lesson recorded
        against `wsc-session-disposition.py`.
        `--verified-at` defaults to now (UTC, second precision).

    advance <record_path>
        Invokes `cutover.advance`, which internally re-runs `cutover.gate`
        and REFUSES the phase bump on non-coverage (plan § C5/D1). Prints the
        returned `verdict_line` + `notes` and exits 0 (verdict rendered) / 1
        (transport or setup error) / 2 (INDETERMINATE -> HALT), mirroring
        `review-coverage-gate.py`'s exit-code contract exactly.

Neither `cutover.gate` nor `cutover.advance` is authored by this chunk (C7)
— they are C4b/C5's pinned op keys. An "unknown op" transport failure at
smoke-test time, before those chunks land, is expected here, not a bug in
this forwarder.

Negative-spec: this forwarder never shells out and never re-execs bash — see
its `.cmd` sibling (generated by `gen-launcher-shim.py`, python-direct, no
bash re-exec) for the Windows-parity half of the same contract (DR-076).
"""
from __future__ import annotations

import datetime
import os
import sys

_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
_LIB_DIR = os.path.join(_SCRIPT_DIR, "lib")
if _LIB_DIR not in sys.path:
    sys.path.insert(0, _LIB_DIR)

import cc_invoke  # noqa: E402  (sys.path mutated above)
from cc_invoke import _resolve_claude_klabauter_root  # noqa: E402

GENERATES = []  # writes only to DoE-side cutover records (state/roadmap/lifecycle-vocab/cutovers/), never under this claude-klabauter checkout — see _repo_root_for's docstring

_TRANSPORT_FAIL = 3

_VERIFIED_BY_KINDS = ("test-node-id", "probe-op-key", "commit-sha")

_SUBCOMMANDS = (
    "subcommands: show <record_path> | "
    "confirm-consumer <record_path> --id <id> --verified-by-kind "
    "<test-node-id|probe-op-key|commit-sha> --verified-by-ref <ref> "
    "[--verified-at <ISO-8601>] | "
    "advance <record_path>"
)

_HELP_FLAGS = ("--help", "-h", "help")


def _usage(prog: str) -> int:
    print(f"usage: {prog} <subcommand> <args...>\n{_SUBCOMMANDS}", file=sys.stderr)
    return 2


def _repo_root_for(record_path: str) -> str:
    """Resolve the git repo root the record lives under.

    Records live DoE-side (`state/roadmap/lifecycle-vocab/cutovers/`, per plan
    § D2/D5), never under this claude-klabauter checkout — the engine call itself
    crosses that boundary (C4c's `resolve_doe_repo_path()`), so this forwarder
    resolves relative to the record's OWN containing repo, not `_SCRIPT_DIR`.
    """
    import subprocess

    abs_record = os.path.abspath(record_path)
    start_dir = os.path.dirname(abs_record) if os.path.isfile(abs_record) else abs_record
    try:
        return subprocess.run(
            ["git", "-C", start_dir, "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        return os.getcwd()


def _run_gate_shaped_op(op_key: str, record_path: str) -> int:
    """Shared trampoline for `show` (cutover.gate) and `advance` (cutover.advance) —
    both return the same coverage_gate-shaped verdict envelope (plan § C4b/C5:
    `verdict_line`, `notes[]`, `exit_code` in {0, 1, 2}), so both subcommands
    share this single call-and-render path. Mirrors
    `review-coverage-gate.py`'s result handling exactly.
    """
    repo_root = _repo_root_for(record_path)
    params = {"record": record_path}

    def _legacy_fn() -> "NoReturn":  # type: ignore[name-defined]
        raise RuntimeError(
            f"cutover-cli: coordinator_core seam absent — no bash fallback for "
            f"{op_key}. Install/repair coordinator_core (CLAUDE_KLABAUTER_ROOT) and retry."
        )

    try:
        result = cc_invoke.route(op_key, params, repo_root, _legacy_fn)
    except RuntimeError as exc:
        print(f"cutover-cli: {op_key}: engine could not compute a verdict ({exc})", file=sys.stderr)
        print("  Verify CLAUDE_KLABAUTER_ROOT and coordinator_core installation (see diagnostics above)", file=sys.stderr)
        return 1

    if not isinstance(result, dict):
        print(f"cutover-cli: {op_key}: malformed result from cc_invoke: not a dict ({result!r})", file=sys.stderr)
        return 1

    verdict = result.get("verdict_line", "")
    notes = result.get("notes") or []
    if not isinstance(notes, list):
        notes = []

    exit_code_raw = result.get("exit_code", 1)
    try:
        exit_code = int(exit_code_raw)
    except (TypeError, ValueError):
        print(f"cutover-cli: {op_key}: unexpected exit_code type {exit_code_raw!r}; treating as 1", file=sys.stderr)
        exit_code = 1

    if exit_code not in (0, 1, 2):
        print(f"cutover-cli: {op_key}: unexpected exit_code {exit_code}; treating as 1", file=sys.stderr)
        exit_code = 1

    if exit_code == 2:
        if verdict:
            print(verdict)
        for note in notes:
            print(note, file=sys.stderr)
        return 2

    if not verdict:
        print(f"cutover-cli: {op_key}: coordinator_core returned empty verdict_line", file=sys.stderr)
        for note in notes:
            print(note, file=sys.stderr)
        return 1

    print(verdict)
    for note in notes:
        print(note, file=sys.stderr)
    return exit_code


def _cmd_show(rest: list[str]) -> int:
    if not rest:
        return _usage("cutover-cli show <record_path>")
    return _run_gate_shaped_op("cutover.gate", rest[0])


def _cmd_advance(rest: list[str]) -> int:
    if not rest:
        return _usage("cutover-cli advance <record_path>")
    return _run_gate_shaped_op("cutover.advance", rest[0])


def _parse_confirm_consumer_flags(tail: list[str]) -> "tuple[dict[str, str], str | None]":
    flags = {"id": "", "verified-by-kind": "", "verified-by-ref": "", "verified-at": ""}
    i = 0
    while i < len(tail):
        tok = tail[i]
        if tok in ("--id", "--verified-by-kind", "--verified-by-ref", "--verified-at"):
            key = tok[2:]
            if i + 1 >= len(tail):
                return flags, f"{tok} requires a value"
            flags[key] = tail[i + 1]
            i += 2
        else:
            return flags, f"unrecognized argument {tok!r}"
    return flags, None


def _cmd_confirm_consumer(rest: list[str]) -> int:
    _USAGE = (
        "cutover-cli confirm-consumer <record_path> --id <id> "
        "--verified-by-kind <test-node-id|probe-op-key|commit-sha> "
        "--verified-by-ref <ref> [--verified-at <ISO-8601>]"
    )
    if not rest:
        return _usage(_USAGE)
    record_path, tail = rest[0], rest[1:]
    flags, err = _parse_confirm_consumer_flags(tail)
    if err:
        print(f"cutover-cli: confirm-consumer: {err}", file=sys.stderr)
        return 2

    if not flags["id"] or not flags["verified-by-kind"] or not flags["verified-by-ref"]:
        print(
            "cutover-cli: confirm-consumer: --id, --verified-by-kind and "
            "--verified-by-ref are all required",
            file=sys.stderr,
        )
        return _usage(_USAGE)

    if flags["verified-by-kind"] not in _VERIFIED_BY_KINDS:
        print(
            f"cutover-cli: confirm-consumer: --verified-by-kind must be one of "
            f"{_VERIFIED_BY_KINDS}, got {flags['verified-by-kind']!r}",
            file=sys.stderr,
        )
        return 2

    verified_at = flags["verified-at"] or datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )

    try:
        claude_klabauter_root = _resolve_claude_klabauter_root()
    except RuntimeError as exc:
        print(f"cutover-cli: confirm-consumer: CLAUDE_KLABAUTER_ROOT resolution failed: {exc}", file=sys.stderr)
        return _TRANSPORT_FAIL
    if claude_klabauter_root not in sys.path:
        sys.path.insert(0, claude_klabauter_root)
    try:
        from coordinator_core.frontmatter import split_frontmatter, rebuild
    except ImportError as exc:
        print(f"cutover-cli: confirm-consumer: coordinator_core.frontmatter not importable: {exc}", file=sys.stderr)
        return _TRANSPORT_FAIL

    import yaml

    try:
        with open(record_path, "r", encoding="utf-8") as fh:
            text = fh.read()
    except OSError as exc:
        print(f"cutover-cli: confirm-consumer: cannot read {record_path}: {exc}", file=sys.stderr)
        return 1

    split = split_frontmatter(text)
    if split is None:
        print(f"cutover-cli: confirm-consumer: {record_path} has no parseable frontmatter", file=sys.stderr)
        return 1

    try:
        fm = yaml.safe_load(split.fm_text) or {}
    except yaml.YAMLError as exc:
        print(f"cutover-cli: confirm-consumer: {record_path} frontmatter is not valid YAML: {exc}", file=sys.stderr)
        return 1

    if not isinstance(fm, dict):
        print(f"cutover-cli: confirm-consumer: {record_path} frontmatter is not a mapping", file=sys.stderr)
        return 1

    confirmed = fm.get("confirmed_consumers")
    if confirmed is None:
        confirmed = []
    if not isinstance(confirmed, list):
        print(f"cutover-cli: confirm-consumer: {record_path} confirmed_consumers is not a list", file=sys.stderr)
        return 1

    confirmed.append(
        {
            "id": flags["id"],
            "verified_by": {
                "kind": flags["verified-by-kind"],
                "ref": flags["verified-by-ref"],
            },
            "verified_at": verified_at,
        }
    )
    fm["confirmed_consumers"] = confirmed

    new_fm_text = yaml.safe_dump(fm, default_flow_style=False, sort_keys=False, allow_unicode=True)
    new_text = rebuild(split, new_fm_text)

    try:
        with open(record_path, "w", encoding="utf-8") as fh:
            fh.write(new_text)
    except OSError as exc:
        print(f"cutover-cli: confirm-consumer: cannot write {record_path}: {exc}", file=sys.stderr)
        return 1

    print(f"confirm-consumer: appended {flags['id']!r} to {record_path}")
    return 0


def main(argv: list[str]) -> int:
    if not argv:
        return _usage("cutover-cli")
    subcmd, rest = argv[0], argv[1:]

    if subcmd in _HELP_FLAGS:
        print(f"usage: cutover-cli <subcommand> <args...>\n{_SUBCOMMANDS}")
        return 0

    if subcmd == "show":
        return _cmd_show(rest)
    if subcmd == "confirm-consumer":
        return _cmd_confirm_consumer(rest)
    if subcmd == "advance":
        return _cmd_advance(rest)

    print(f"cutover-cli: unknown subcommand {subcmd!r}", file=sys.stderr)
    return _usage("cutover-cli")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
